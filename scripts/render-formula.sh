#!/bin/sh
# Render the Homebrew formula for one release, for the omkar-dev/velocity
# tap (github.com/omkar-dev/homebrew-velocity, file Formula/velocity.rb).
#
#   scripts/render-formula.sh <version> [SHA256SUMS] > velocity.rb
#
# SHA256SUMS is the release's checksum file (`<sha256>  <tarball>` lines,
# the tarballs named velocity-<version>-<target>.tar.gz). The release
# workflow renders the formula with it, attaches it to the GitHub release as
# velocity.rb and pushes it to the tap.
#
# Without SHA256SUMS the formula is HEAD-only (`brew install --HEAD`, a
# source build of main): it never points at release assets it has no
# checksums for, which may not exist yet. That is the Formula/velocity.rb
# committed here; CI checks it matches this script's output.
set -eu

version=${1:?usage: render-formula.sh <version> [SHA256SUMS]}
sums=${2:-}
version=${version#v}
repo=${VELOCITY_REPO:-omkar-dev/velocity}

case $version in
    [0-9]*.[0-9]*.[0-9]*) ;;
    *) echo "render-formula: '$version' is not a version (X.Y.Z)" >&2; exit 1 ;;
esac

sha_for() {
    target=$1
    file="velocity-${version}-${target}.tar.gz"
    sha=$(awk -v f="$file" '$2 == f || $2 == "*" f { print $1 }' "$sums")
    case $sha in
        [0-9a-f]*) [ ${#sha} -eq 64 ] && { echo "$sha"; return; } ;;
    esac
    echo "render-formula: no sha256 for $file in $sums" >&2
    exit 1
}

if [ -z "$sums" ]; then
    generated="(HEAD only: no release checksums given); edit the script,
# not this file. Release builds of it are attached to each GitHub release."
    # Only the version number of a source build of main isn't known here.
    version_test='assert_match "velocity", shell_output("#{bin}/velocity --version")'
else
    generated="for v${version}; edit the script,
# not this file. Tap: brew install omkar-dev/velocity/velocity"
    version_test='assert_match version.to_s, shell_output("#{bin}/velocity --version")'
fi

cat <<FORMULA
# Generated by scripts/render-formula.sh ${generated}
class Velocity < Formula
  desc "Fast, reliable mobile UI testing framework"
  homepage "https://github.com/${repo}"
  license "AGPL-3.0-only"

  # \`brew install --HEAD\` builds main from source, web UI included.
  head do
    url "https://github.com/${repo}.git", branch: "main"

    depends_on "node" => :build
    depends_on "rust" => :build
  end
FORMULA

if [ -n "$sums" ]; then
    mac_arm=$(sha_for aarch64-apple-darwin)
    mac_intel=$(sha_for x86_64-apple-darwin)
    linux_arm=$(sha_for aarch64-unknown-linux-musl)
    linux_intel=$(sha_for x86_64-unknown-linux-musl)
    base="https://github.com/${repo}/releases/download/v${version}"
    cat <<FORMULA

  # Prebuilt release binaries (the Linux ones are static musl builds); each
  # includes the \`velocity inspect\` web UI.
  on_macos do
    on_arm do
      url "${base}/velocity-${version}-aarch64-apple-darwin.tar.gz"
      sha256 "${mac_arm}"
    end
    on_intel do
      url "${base}/velocity-${version}-x86_64-apple-darwin.tar.gz"
      sha256 "${mac_intel}"
    end
  end

  on_linux do
    on_arm do
      url "${base}/velocity-${version}-aarch64-unknown-linux-musl.tar.gz"
      sha256 "${linux_arm}"
    end
    on_intel do
      url "${base}/velocity-${version}-x86_64-unknown-linux-musl.tar.gz"
      sha256 "${linux_intel}"
    end
  end
FORMULA
fi

cat <<FORMULA

  def install
    if build.head?
      # The inspector embeds frontend/dist at compile time; build.rs never
      # runs npm, so build the UI first.
      cd "crates/velocity-inspector/frontend" do
        system "npm", "ci", *std_npm_args(prefix: false)
        system "npm", "run", "build"
      end
      system "cargo", "install", "--locked", *std_cargo_args(path: "velocity-cli")
    else
      bin.install "velocity"
    end
  end

  test do
    ${version_test}
    assert_match "velocity", shell_output("#{bin}/velocity version")
  end
end
FORMULA
