//! `velocity api scaffold` on a petstore-like spec: the suite's shape,
//! links between requests, mined checks, `$ref`s, and `--confirm` against
//! a server on 127.0.0.1 that breaks one promise of its spec.

use std::io::{BufRead, BufReader, Read, Write};
use std::net::TcpListener;
use std::sync::atomic::{AtomicUsize, Ordering};
use std::sync::Arc;

use serde_json::{json, Value};
use velocity_api::openapi::{confirm, render, scaffold, Options, Scaffold, Spec};
use velocity_common::{Capture, HttpRequest, StatusCheck};

const PETSTORE: &str = include_str!("fixtures/petstore.yaml");

fn petstore() -> Scaffold {
    let spec = Spec::parse(PETSTORE).unwrap();
    scaffold(
        &spec,
        &Options {
            source: "petstore.yaml".into(),
            ..Default::default()
        },
    )
    .unwrap()
}

fn step<'a>(s: &'a Scaffold, test: &str, label: &str) -> &'a HttpRequest {
    &s.tests
        .iter()
        .find(|t| t.name == test)
        .unwrap()
        .steps
        .iter()
        .find(|st| st.label.starts_with(label))
        .unwrap_or_else(|| panic!("no {label} in {test}"))
        .request
}

#[test]
fn one_test_per_resource_with_producers_first() {
    let s = petstore();
    let names: Vec<&str> = s.tests.iter().map(|t| t.name.as_str()).collect();
    assert_eq!(names, ["pets", "stores"]);
    let pets: Vec<&str> = s.tests[0]
        .steps
        .iter()
        .map(|st| st.label.as_str())
        .collect();
    assert_eq!(
        pets,
        [
            "POST /pets (createPet)",
            "GET /pets (listPets)",
            "GET /pets/{petId} (getPet)",
            "DELETE /pets/{petId} (deletePet)"
        ]
    );
    assert_eq!(
        s.config.base_url.as_deref(),
        Some("https://petstore.example.com/v1")
    );
    assert_eq!(
        s.config.headers,
        vec![(
            "Authorization".to_string(),
            "Bearer ${API_TOKEN}".to_string()
        )]
    );
}

#[test]
fn a_created_id_is_captured_and_used_by_name() {
    let s = petstore();
    let create = step(&s, "pets", "POST /pets");
    assert_eq!(
        create.capture,
        vec![("PET_ID".into(), Capture::Json("$.id".into()))]
    );
    // Required fields only, the enum's first value; the readOnly id is the server's.
    assert_eq!(
        create.json,
        Some(json!({ "name": "example", "status": "available" }))
    );
    assert_eq!(step(&s, "pets", "GET /pets/").url, "/pets/${PET_ID}");
    assert_eq!(step(&s, "pets", "DELETE").url, "/pets/${PET_ID}");
    // An order needs a pet: another resource's create runs first, in the
    // order's own test (captures don't cross tests).
    let stores = &s.tests[1].steps;
    assert_eq!(stores[0].label, "POST /pets (createPet)");
    assert!(stores[0].notes[0].starts_with("setup:"));
    let order = &stores[1].request;
    assert_eq!(order.url, "/stores/${API_STORE_ID}/orders");
    assert_eq!(
        order.json,
        Some(json!({ "petId": "${PET_ID}", "quantity": 2 }))
    );
    assert_eq!(
        order.headers,
        vec![("X-Request-Id".into(), "${API_X_REQUEST_ID}".into())]
    );
    let vars: Vec<&str> = s.variables.iter().map(|(n, _)| n.as_str()).collect();
    assert_eq!(vars, ["API_TOKEN", "API_STORE_ID", "API_X_REQUEST_ID"]);
}

#[test]
fn checks_are_read_from_the_response_schema() {
    let s = petstore();
    let get = step(&s, "pets", "GET /pets/");
    assert_eq!(get.expect.status, Some(StatusCheck::Code(200)));
    let checks: Vec<(String, Value)> = get
        .expect
        .json
        .iter()
        .map(|(p, m)| (p.clone(), serde_json::to_value(m).unwrap()))
        .collect();
    let at = |p: &str| {
        checks
            .iter()
            .find(|(q, _)| q == p)
            .map(|(_, m)| m.clone())
            .unwrap()
    };
    assert_eq!(at("$"), json!({ "type": "object" }));
    assert_eq!(
        at("$.status")["oneOf"],
        json!(["available", "pending", "sold"])
    );
    assert_eq!(at("$.name")["length"], json!({ "gte": 1.0, "lte": 50.0 }));
    assert!(at("$.id")["matches"]
        .as_str()
        .unwrap()
        .contains("[0-9a-fA-F]{8}"));
    assert!(at("$.createdAt")["matches"]
        .as_str()
        .unwrap()
        .starts_with(r"\d{4}"));
    assert_eq!(at("$.createdAt")["exists"], json!(true));
    // `tag` is optional: an absent one is no failure.
    assert!(!checks.iter().any(|(p, _)| p == "$.tag"));
    assert_eq!(step(&s, "pets", "GET /pets (").expect.json[0].0, "$");
    assert_eq!(
        step(&s, "pets", "DELETE").expect.status,
        Some(StatusCheck::Code(204))
    );
}

#[test]
fn the_written_suite_reads_back_and_every_step_validates() {
    let s = petstore();
    let yaml = render(&s).unwrap();
    assert!(yaml
        .starts_with("# Generated by `velocity api scaffold` from petstore.yaml (Petstore 1.0.0)"));
    assert!(yaml.contains("#   API_TOKEN"), "{yaml}");
    assert!(!yaml.contains("appId"));
    let doc: Value = serde_yaml::from_str(&yaml).unwrap();
    let mut n = 0;
    for t in doc["tests"].as_array().unwrap() {
        for st in t["steps"].as_array().unwrap() {
            let req: HttpRequest = serde_json::from_value(st["http"].clone()).unwrap();
            velocity_api::validate(&req).unwrap();
            n += 1;
        }
    }
    assert_eq!(n, s.requests());
}

/// The petstore, except its pets have a status the spec doesn't list.
fn serve(unsafe_sent: Arc<AtomicUsize>) -> String {
    let listener = TcpListener::bind("127.0.0.1:0").unwrap();
    let addr = listener.local_addr().unwrap();
    std::thread::spawn(move || {
        for mut conn in listener.incoming().flatten() {
            let mut reader = BufReader::new(conn.try_clone().unwrap());
            let mut line = String::new();
            if reader.read_line(&mut line).is_err() {
                continue;
            }
            let mut len = 0;
            let mut authorized = false;
            loop {
                let mut h = String::new();
                reader.read_line(&mut h).unwrap();
                let h = h.trim_end().to_ascii_lowercase();
                if h.is_empty() {
                    break;
                }
                if let Some(v) = h.strip_prefix("content-length:") {
                    len = v.trim().parse().unwrap();
                }
                authorized |= h == "authorization: bearer tok";
            }
            let mut body = vec![0; len];
            reader.read_exact(&mut body).unwrap();
            let mut parts = line.split_whitespace();
            let (method, target) = (parts.next().unwrap_or(""), parts.next().unwrap_or(""));
            let pet = json!({
                "id": "0b6b3c38-8f3c-4e0e-9c55-6f9f7c1d2a11", "name": "Rex",
                "status": "adopted", "createdAt": "2026-10-30T09:00:00Z"
            });
            let (status, reply) = match (method, target) {
                _ if !authorized => (401, json!({ "error": "no token" })),
                ("GET", "/v1/pets") => (200, json!([pet])),
                ("GET", "/v1/pets/0b6b3c38-8f3c-4e0e-9c55-6f9f7c1d2a11") => (200, pet),
                ("GET", _) => (404, json!({ "error": "no such pet" })),
                _ => {
                    unsafe_sent.fetch_add(1, Ordering::SeqCst);
                    (201, json!({}))
                }
            };
            let body = reply.to_string();
            let _ = write!(
                conn,
                "HTTP/1.1 {status} X\r\ncontent-type: application/json\r\ncontent-length: {}\r\nconnection: close\r\n\r\n{body}",
                body.len()
            );
        }
    });
    format!("http://{addr}/v1")
}

#[tokio::test]
async fn confirm_drops_what_the_server_disproves_and_sends_only_gets() {
    let unsafe_sent = Arc::new(AtomicUsize::new(0));
    let spec = Spec::parse(PETSTORE).unwrap();
    let mut s = scaffold(
        &spec,
        &Options {
            base_url: Some(serve(unsafe_sent.clone())),
            ..Default::default()
        },
    )
    .unwrap();
    let env = |name: &str| match name {
        "API_TOKEN" => Some("tok".to_string()),
        "PET_ID" => Some("0b6b3c38-8f3c-4e0e-9c55-6f9f7c1d2a11".to_string()),
        _ => None,
    };
    let report = confirm(&mut s, &env).await.unwrap();
    assert_eq!(
        unsafe_sent.load(Ordering::SeqCst),
        0,
        "confirm mode sent a POST or DELETE"
    );
    assert_eq!(report.sent, 2, "{report:?}");
    let dropped: Vec<(&str, &str)> = report
        .dropped
        .iter()
        .map(|f| (f.request.as_str(), f.path.as_str()))
        .collect();
    assert_eq!(dropped, [("GET /pets/{petId} (getPet)", "$.status")]);
    assert!(report.dropped[0].why.contains("\"adopted\""), "{report:?}");
    assert!(report.held > 4);
    // Every POST and DELETE is listed as not sent.
    let not_sent = report
        .skipped
        .iter()
        .filter(|f| f.why.contains("never sent"))
        .count();
    assert_eq!(not_sent, 4, "{:?}", report.skipped);
    let get = step(&s, "pets", "GET /pets/");
    assert!(!get.expect.json.iter().any(|(p, _)| p == "$.status"));
    let yaml = render(&s).unwrap();
    assert!(yaml.contains("# --confirm dropped `$.status`"), "{yaml}");
}

#[tokio::test]
async fn confirm_without_a_server_says_what_to_set() {
    let spec = Spec::parse(&PETSTORE.replace(
        "  - url: https://petstore.example.com/v1\n",
        "  - url: /v1\n",
    ))
    .unwrap();
    let mut s = scaffold(&spec, &Options::default()).unwrap();
    assert_eq!(s.config.base_url.as_deref(), Some("${API_URL}/v1"));
    let e = confirm(&mut s, &|_| None).await.unwrap_err().to_string();
    assert!(e.contains("set ${API_URL} or pass --base-url"), "{e}");
}
